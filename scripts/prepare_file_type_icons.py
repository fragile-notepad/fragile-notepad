"""Prepare large file-type artwork and its catalog lookup for embedding.

resvg preserves the source SVGs' gradients, transforms, and clipping. The
application embeds straight RGBA pixels and needs no SVG or Python runtime.
"""

from __future__ import annotations

import argparse
from hashlib import sha256
from importlib.metadata import version
from io import BytesIO
import json
from pathlib import Path
import re

from PIL import Image
import resvg_py

ROOT = Path(__file__).resolve().parents[1]
SIZE = 64


def write_if_changed(path: Path, content: str) -> None:
    if not path.exists() or path.read_text(encoding="utf-8") != content:
        path.write_text(content, encoding="utf-8", newline="\n")


def prepare(icons_dir: Path, out_dir: Path) -> None:
    catalog = json.loads((icons_dir / "catalog.json").read_text(encoding="utf-8"))
    raster_dir = out_dir / "file-type-icons"
    raster_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = raster_dir / "manifest.json"
    try:
        previous = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (FileNotFoundError, ValueError):
        previous = {}
    renderer = f"{SIZE}:resvg-py:{version('resvg-py')}:Pillow:{version('Pillow')}"
    compiler = Path(__file__).read_bytes()
    manifest = {}
    generated = ["// Generated by scripts/prepare_file_type_icons.py. Do not edit."]
    extensions = {}
    names = set()

    for entry in catalog:
        name = entry["id"]
        if not re.fullmatch(r"[a-z][a-z0-9_]*", name) or name in names:
            raise ValueError(f"Invalid or duplicate file-type id: {name!r}")
        names.add(name)
        source = (icons_dir / "svg" / f"{name}.svg").read_bytes()
        digest = sha256(compiler + renderer.encode() + source).hexdigest()
        raster = raster_dir / f"{name}.rgba"
        if previous.get(name) != digest or not raster.exists() or raster.stat().st_size != SIZE * SIZE * 4:
            png = resvg_py.svg_to_bytes(
                svg_string=source.decode("utf-8"), width=SIZE, height=SIZE
            )
            with Image.open(BytesIO(png)) as image:
                if image.size != (SIZE, SIZE):
                    raise ValueError(f"Unexpected raster dimensions for {name}: {image.size}")
                raster.write_bytes(image.convert("RGBA").tobytes())
        manifest[name] = digest
        generated.extend([
            f"static {name.upper()}: LazyLock<image::Handle> = LazyLock::new(|| {{",
            f"    image::Handle::from_rgba({SIZE}, {SIZE}, include_bytes!(concat!(",
            f'        env!("OUT_DIR"), "/file-type-icons/{name}.rgba"',
            "    )).as_slice())",
            "});",
        ])
        for extension in entry["extensions"]:
            if not extension.startswith(".") or extension != extension.lower() or extension in extensions:
                raise ValueError(f"Invalid or duplicate file extension: {extension!r}")
            extensions[extension] = name

    if not {"text", "other"} <= names:
        raise ValueError("The file-type catalog must provide text and other fallback icons")
    generated.extend([
        "fn handle_for_extension(extension: &str) -> &'static image::Handle {",
        "    match extension {",
    ])
    for extension, name in sorted(extensions.items()):
        generated.append(f"        {json.dumps(extension[1:])} => &{name.upper()},")
    generated.extend(["        _ => &OTHER,", "    }", "}", ""])
    write_if_changed(out_dir / "file_type_icons.rs", "\n".join(generated))
    write_if_changed(manifest_path, json.dumps(manifest, indent=2, sort_keys=True) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--icons-dir", type=Path, default=ROOT / "assets/icons/file-types")
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()
    prepare(args.icons_dir, args.out_dir)


if __name__ == "__main__":
    main()
